#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  checkCatalogPair,
  flattenCatalog,
  interpolationNames,
  pluralSuffix,
  readCatalog,
} from './i18n-catalog-quality.mjs'

// An opt-in pilot, kept separate from i18next's global type graph.
export const translationScopes = {
  layout: { dynamicFamilies: ['nav'] },
  appearance: {
    dynamicFamilies: ['presets', 'modes', 'densities', 'scales', 'motions'],
  },
  'chat.aiWorkspace': { dynamicFamilies: [] },
}
export const generatedTypesPath =
  'src/locales/translation-contracts.generated.ts'

function subtree(catalog, scope) {
  return scope.split('.').reduce((value, key) => value?.[key], catalog)
}

/** Reuses literal AST evaluation; catalog modules are never executed. */
export function createTranslationContract(
  readSource,
  scopes = translationScopes,
) {
  const catalogs = Object.fromEntries(
    ['en-US', 'zh-CN'].map((locale) => [
      locale,
      readCatalog(readSource, `src/locales/${locale}/index.ts`),
    ]),
  )
  const contracts = {}
  const review = []
  for (const [scope, metadata] of Object.entries(scopes)) {
    const english = subtree(catalogs['en-US'], scope)
    const chinese = subtree(catalogs['zh-CN'], scope)
    if (!english || !chinese)
      throw new Error(`Missing typed translation scope: ${scope}`)
    const findings = checkCatalogPair(english, chinese)
    if (findings.length)
      throw new Error(
        `${scope}: ${findings.map((item) => `${item.rule}:${item.key}`).join(', ')}`,
      )
    const rows = flattenCatalog(english)
    const chineseRows = flattenCatalog(chinese)
    const keys = new Map()
    for (const [key, text] of rows) {
      const canonical = key.replace(pluralSuffix, '')
      const parameters = keys.get(canonical) ?? new Set()
      for (const parameter of interpolationNames(text))
        parameters.add(parameter)
      if (canonical !== key) parameters.add('count')
      keys.set(canonical, parameters)
      review.push({
        scope,
        key,
        dynamic: metadata.dynamicFamilies.some((family) =>
          key.startsWith(`${family}.`),
        ),
        english: text,
        chinese: chineseRows.get(key) ?? chineseRows.get(`${canonical}_other`),
      })
    }
    contracts[scope] = Object.fromEntries(
      [...keys]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, values]) => [key, [...values].sort()]),
    )
  }
  const members = Object.entries(contracts).map(([scope, keys]) => {
    const properties = Object.entries(keys).map(([key, parameters]) => {
      const type = parameters.length
        ? `{ ${parameters.map((name) => `${JSON.stringify(name)}: ${name === 'count' ? 'number' : 'string | number'}`).join('; ')} }`
        : 'undefined'
      return `    ${JSON.stringify(key)}: ${type}`
    })
    return `  ${JSON.stringify(scope)}: {\n${properties.join('\n')}\n  }`
  })
  return {
    source: `// Generated by scripts/generate-i18n-types.mjs. Do not edit.\n// Type-only output: importing this contract never loads a locale catalog.\nexport interface TranslationContracts {\n${members.join('\n')}\n}\n`,
    review,
  }
}

export function runTypeGeneration(
  args = process.argv.slice(2),
  root = process.cwd(),
) {
  const allowed = new Set(['--check', '--review'])
  for (const arg of args)
    if (!allowed.has(arg)) throw new Error(`Unknown argument: ${arg}`)
  const result = createTranslationContract((file) => {
    try {
      return readFileSync(path.join(root, file), 'utf8')
    } catch {
      return undefined
    }
  })
  if (args.includes('--review')) return { ...result, matches: true }
  const output = path.join(root, generatedTypesPath)
  if (args.includes('--check')) {
    let current
    try {
      current = readFileSync(output, 'utf8')
    } catch {
      /* A missing generated contract must fail the drift check. */
    }
    // Prettier may choose single quotes or wrap object members. Formatting is
    // irrelevant here; use the same formatter for generation and comparison.
    return { ...result, current, output }
  }
  return { ...result, output }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const args = process.argv.slice(2)
    const result = runTypeGeneration(args)
    if (args.includes('--review')) {
      console.log(JSON.stringify(result.review, null, 2))
    } else {
      const { format, resolveConfig } = await import('prettier')
      const source = await format(result.source, {
        ...(await resolveConfig(result.output)),
        filepath: result.output,
      })
      if (args.includes('--check')) {
        if (result.current !== source) {
          console.error(
            'Translation contracts are stale. Run node scripts/generate-i18n-types.mjs.',
          )
          process.exitCode = 1
        } else
          console.log(
            'Typed translation contracts match the selected bilingual catalogs.',
          )
      } else {
        writeFileSync(result.output, source)
        console.log(`Generated ${generatedTypesPath}.`)
      }
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  }
}
