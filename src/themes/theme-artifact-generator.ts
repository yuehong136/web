import type { DesignTokens } from './tokens'
import {
  APPEARANCE_PRESETS,
  type AppearancePreset,
  type ResolvedTheme,
} from './appearance'
import { buildPresetTokens } from './preset-tokens'
import { generateThemeCSS } from './theme-css-generator'

type TokenSets = Record<ResolvedTheme, DesignTokens>
export function createPresetTokenSets(base: TokenSets) {
  return Object.fromEntries(
    APPEARANCE_PRESETS.map((preset) => [
      preset,
      {
        light: buildPresetTokens(base.light, 'light', preset),
        dark: buildPresetTokens(base.dark, 'dark', preset),
      },
    ]),
  ) as Record<AppearancePreset, TokenSets>
}

/** Adjacent values share CSS/color prefixes; retain readable suffixes, once. */
function encodeValues(values: string[]): string[] {
  let previous = ''
  return values.map((value) => {
    let shared = 0
    while (
      shared < previous.length &&
      shared < value.length &&
      previous[shared] === value[shared]
    )
      shared += 1
    const encoded = `${shared.toString(36)}:${value.slice(shared)}`
    previous = value
    return encoded
  })
}

export function generatePresetValuesModule(base: TokenSets): string {
  const sets = createPresetTokenSets(base)
  const themes = APPEARANCE_PRESETS.flatMap((preset) => [
    sets[preset].light,
    sets[preset].dark,
  ])
  const names = (Object.keys(base.light) as (keyof DesignTokens)[]).sort()
  const values = [
    ...new Set(themes.flatMap((tokens) => Object.values(tokens))),
  ].sort()
  const valueIndices = new Map(values.map((value, index) => [value, index]))
  const width = (values.length - 1).toString(36).length
  const combinations: string[] = []
  const references = names.map((name) => {
    let indices = themes.map((tokens) => valueIndices.get(tokens[name])!)
    if (indices.every((value) => value === indices[0])) {
      indices = indices.slice(0, 1)
    } else if (indices.every((value, index) => value === indices[index % 2])) {
      indices = indices.slice(0, 2)
    }
    const signature = indices
      .map((value) => value.toString(36).padStart(width, '0'))
      .join('')
    let group = combinations.indexOf(signature)
    if (group === -1) {
      group = combinations.length
      combinations.push(signature)
    }
    return group.toString(36)
  })
  const referenceWidth = (combinations.length - 1).toString(36).length
  const referenceRow = references
    .map((reference) => reference.padStart(referenceWidth, '0'))
    .join('')
  const presets = APPEARANCE_PRESETS.map((preset) => {
    const index = APPEARANCE_PRESETS.indexOf(preset) * 2
    const light =
      preset === 'studio' ? 'lightTokenValues' : `createTokenSet(${index})`
    const dark =
      preset === 'studio' ? 'darkTokenValues' : `createTokenSet(${index + 1})`
    return `  ${preset}: Object.freeze({ light: ${light}, dark: ${dark} }),`
  }).join('\n')
  return `// AUTO-GENERATED by src/themes/build-themes.ts — DO NOT EDIT BY HAND.
// Source: theme-generator.ts and preset-palettes.ts. Run npm run build:themes.
import { defaultTokens, type DesignTokens } from './tokens'
import type { AppearancePreset, ResolvedTheme } from './appearance'

// Reuse the existing token-name registry and share identical values across all
// eight themes. Prefix rows are "shared characters in base 36:literal suffix".
const tokenNames = (Object.keys(defaultTokens) as (keyof DesignTokens)[]).sort()
const valueRows = ${JSON.stringify(encodeValues(values))}
const values: string[] = []
for (const row of valueRows) {
  const separator = row.indexOf(':')
  const shared = Number.parseInt(row.slice(0, separator), 36)
  const previous = values.at(-1) ?? ''
  values.push(previous.slice(0, shared) + row.slice(separator + 1))
}
// Each combination is either one constant, a light/dark pair, or eight values
// ordered by preset then mode. Numeric references avoid repeating token names.
const combinations = ${JSON.stringify(combinations.join('.'))}.split('.').map((row) => {
  const combination: string[] = []
  for (let index = 0; index < row.length; index += ${width}) {
    combination.push(values[Number.parseInt(row.slice(index, index + ${width}), 36)])
  }
  return combination
})
const references = ${JSON.stringify(referenceRow)}.match(/.{${referenceWidth}}/g)!.map((value) => Number.parseInt(value, 36))
function createTokenSet(themeIndex: number): Readonly<DesignTokens> {
  return Object.freeze(Object.fromEntries(tokenNames.map((name, index) => {
    const combination = combinations[references[index]]
    return [name, combination[themeIndex % combination.length]]
  }))) as Readonly<DesignTokens>
}
export const lightTokenValues = createTokenSet(0)
export const darkTokenValues = createTokenSet(1)
export const presetTokenValues: Readonly<Record<AppearancePreset, Readonly<Record<ResolvedTheme, Readonly<DesignTokens>>>>> = Object.freeze({
${presets}
})
`
}

export function generatePresetCSS(
  base: TokenSets,
  mode: ResolvedTheme,
): string {
  const sets = createPresetTokenSets(base)
  return APPEARANCE_PRESETS.map((preset) =>
    generateThemeCSS(
      sets[preset][mode],
      mode,
      preset === 'studio' ? undefined : preset,
    ),
  ).join('\n')
}
